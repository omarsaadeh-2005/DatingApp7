import { Component, HostListener, OnInit, ViewChild } from '@angular/core';
import { NgForm } from '@angular/forms';
import { ToastrService } from 'ngx-toastr';
import { take } from 'rxjs';
import { Member } from 'src/app/_models/member';
import { User } from 'src/app/_models/user';
import { AccountService } from 'src/app/_services/account.service';
import { MembersService } from 'src/app/_services/members.service';
import { environment } from 'src/environments/environment';

@Component({
  selector: 'app-member-edit',
  templateUrl: './member-edit.component.html',
  styleUrls: ['./member-edit.component.css'],
})
export class MemberEditComponent implements OnInit {
  @ViewChild('editForm') editForm: NgForm | undefined;
  imageUrl = environment.imageUrl;

  // AI Feature State Variables
  isAiModalOpen = false;
  aiKeywords = '';
  isGeneratingBio = false;

  @HostListener('window:beforeunload', ['$event']) unloadNotification($event: any) {
    if (this.editForm?.dirty) {
      $event.returnValue = true;
    }
  }

  member: Member | undefined;
  user: User | null = null;

  constructor(
    private accountService: AccountService, 
    private memberService: MembersService, 
    private toastr: ToastrService
  ) { 
    this.accountService.currentUser$.pipe(take(1)).subscribe({
      next: user => this.user = user
    });
  }

  ngOnInit(): void {
    this.loadMember();
  }

  loadMember() {
    if (!this.user) return;
    this.memberService.getMember(this.user.username).subscribe({
      next: member => this.member = member
    });
  }

  updateMember() {
    this.memberService.updateMember(this.editForm?.value).subscribe({
      next: _ => {
        this.toastr.success("Profile updated successfully");
        this.editForm?.reset(this.member);
      }
    });
  }

  // AI Bio Generation Handler
  generateBioWithAi() {
    if (!this.aiKeywords.trim()) {
      this.toastr.warning('Please enter a few keywords or bullet points first!');
      return;
    }

    this.isGeneratingBio = true;
    this.memberService.generateBio(this.aiKeywords).subscribe({
      next: res => {
        if (this.member) {
          this.member.introduction = res.bio;
        }
        this.isGeneratingBio = false;
        this.isAiModalOpen = false;
        this.aiKeywords = '';
        this.editForm?.control.markAsDirty(); // Triggers the "Save changes" button!
        this.toastr.success('Bio generated by AI! Click "Save changes" to apply.');
      },
      error: err => {
        this.isGeneratingBio = false;
        this.toastr.error(err.error || 'Failed to generate bio with AI.');
      }
    });
  }
}